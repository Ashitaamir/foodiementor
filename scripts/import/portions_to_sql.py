"""
Build a SQL migration that adds portion sizes (e.g. "1 medium chapati") to CoFID foods.

Every line is checked before anything is written:
- the CoFID code must match the CoFID name (so a portion can't attach to the wrong food)
- usda_fndds weights must exactly match a portion weight in the USDA FNDDS file
- at most one default portion per food

Usage:
  python3 scripts/import/portions_to_sql.py data/portions/uk_cofid.txt \
      data/raw/cofid/CoFID_2021.xlsx data/raw/fndds/FNDDS_2021-2023.zip OUTPUT.sql
"""
import json
import sys
import zipfile

from cofid_to_sql import SHEET_NAME, read_sheet, sql_value

FNDDS_VERSION = "FNDDS 2021-2023"
SOURCES = {"usda_fndds", "foodiementor_estimate"}


def load_fndds_weights(zip_path):
    """FNDDS food code -> set of portion gram weights."""
    with zipfile.ZipFile(zip_path) as z:
        foods = json.loads(z.read(z.namelist()[0]))["SurveyFoods"]
    return {
        str(f["foodCode"]): {round(float(p["gramWeight"]), 2) for p in f.get("foodPortions", [])}
        for f in foods
    }


def main(portion_path, xlsx_path, fndds_zip, out_path):
    names = {}
    for r in read_sheet(xlsx_path, SHEET_NAME)[3:]:  # rows 1-3 are headers
        if len(r) > 1 and r[0]:
            names.setdefault(r[0], r[1])  # keep first, same as the import
    fndds = load_fndds_weights(fndds_zip)

    statements, errors = [], []
    seen, defaults = set(), set()
    with open(portion_path, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = [p.strip() for p in line.split("|")]
            if len(parts) != 7:
                errors.append(f"line {n}: expected 7 fields separated by '|'")
                continue
            code, name, label, grams_text, source, fndds_code, default = parts

            if names.get(code) != name:
                errors.append(f"line {n}: {code} is {names.get(code)!r} in CoFID, not {name!r}")
                continue
            if (code, label) in seen:
                errors.append(f"line {n}: {code} already has a portion called {label!r}")
                continue
            if source not in SOURCES:
                errors.append(f"line {n}: unknown source {source!r}")
                continue
            try:
                grams = round(float(grams_text), 2)
            except ValueError:
                errors.append(f"line {n}: grams {grams_text!r} is not a number")
                continue
            if not 0 < grams <= 5000:
                errors.append(f"line {n}: grams {grams} out of range")
                continue
            if source == "usda_fndds":
                if grams not in fndds.get(fndds_code, set()):
                    errors.append(f"line {n}: FNDDS {fndds_code} has no {grams} g portion")
                    continue
                note = f"{FNDDS_VERSION} food code {fndds_code}"
            else:
                note = None
            if default not in ("", "default"):
                errors.append(f"line {n}: last field must be empty or 'default'")
                continue
            if default and code in defaults:
                errors.append(f"line {n}: {code} already has a default portion")
                continue

            seen.add((code, label))
            if default:
                defaults.add(code)
            statements.append(
                "insert into public.portion_sizes (food_id, label, grams, source, source_note, is_default)\n"
                f"select f.id, {sql_value(label)}, {grams:.2f}, {sql_value(source)}, {sql_value(note)}, "
                f"{'true' if default else 'false'}\n"
                f"from public.foods f where f.source = 'uk_cofid' and f.source_food_id = {sql_value(code)}\n"
                "on conflict (food_id, label) do update set\n"
                "  grams = excluded.grams, source = excluded.source,\n"
                "  source_note = excluded.source_note, is_default = excluded.is_default;"
            )

    if errors:
        sys.exit("Portion file has problems — nothing written:\n" + "\n".join(errors))

    with open(out_path, "w", encoding="utf-8") as f:
        f.write(
            "-- Generated by scripts/import/portions_to_sql.py from data/portions/uk_cofid.txt — do not edit by hand.\n"
            "-- usda_fndds weights: U.S. Department of Agriculture, Agricultural Research Service.\n"
            "-- FoodData Central (FNDDS 2021-2023). Public domain (CC0 1.0).\n\n"
            + "\n\n".join(statements) + "\n"
        )
    print(f"Wrote {len(statements)} portions for {len({c for c, _ in seen})} foods to {out_path}")


if __name__ == "__main__":
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    main(*sys.argv[1:])
