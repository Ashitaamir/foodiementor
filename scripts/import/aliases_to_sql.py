"""
Build a SQL migration that adds search aliases (other names/spellings) to CoFID foods.

Reads an alias file, checks every food code AND name against the CoFID Excel
file (so an alias can never attach to the wrong food), and writes UPDATE
statements. Aliases are search words only — they never change nutrition values.

Usage:
  python3 scripts/import/aliases_to_sql.py data/aliases/uk_cofid.txt data/raw/cofid/CoFID_2021.xlsx OUTPUT.sql
"""
import sys

from cofid_to_sql import SHEET_NAME, read_sheet, sql_value


def main(alias_path, xlsx_path, out_path):
    names = {}
    for r in read_sheet(xlsx_path, SHEET_NAME)[3:]:  # rows 1-3 are headers
        if len(r) > 1 and r[0]:
            names.setdefault(r[0], r[1])  # keep first, same as the import

    statements, errors, seen = [], [], set()
    with open(alias_path, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = [p.strip() for p in line.split("|")]
            if len(parts) != 3:
                errors.append(f"line {n}: expected 'code | aliases | name'")
                continue
            code, alias_text, name = parts
            if code in seen:
                errors.append(f"line {n}: code {code} appears twice")
                continue
            if names.get(code) != name:
                errors.append(f"line {n}: {code} is {names.get(code)!r} in CoFID, not {name!r}")
                continue
            seen.add(code)
            aliases = list(dict.fromkeys(a.strip().lower() for a in alias_text.split(",") if a.strip()))
            statements.append(
                "update public.foods set aliases = array["
                + ", ".join(sql_value(a) for a in aliases)
                + f"]::text[] where source = 'uk_cofid' and source_food_id = {sql_value(code)};"
            )

    if errors:
        sys.exit("Alias file has problems — nothing written:\n" + "\n".join(errors))

    with open(out_path, "w", encoding="utf-8") as f:
        f.write(
            "-- Generated by scripts/import/aliases_to_sql.py from data/aliases/uk_cofid.txt — do not edit by hand.\n"
            "-- Search aliases only; nutrition values are not changed.\n\n"
            + "\n".join(statements) + "\n"
        )
    print(f"Wrote aliases for {len(statements)} foods to {out_path}")


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
