"""
Build a SQL migration that loads USDA FNDDS 2021-2023 portion weights
(e.g. "1 cup", "1 tablespoon", "1 slice") for the USDA foods already in public.foods.

Source: U.S. Department of Agriculture, Agricultural Research Service.
FoodData Central (FNDDS 2021-2023). Public domain (CC0 1.0).
USDA's "Quantity not specified" becomes "1 typical serving", the food's default portion.

Usage:
  python3 scripts/import/fndds_portions_to_sql.py data/raw/fndds/FNDDS_2021-2023.zip OUTPUT.sql
"""
import json
import sys
import zipfile

from cofid_to_sql import sql_value

FNDDS_VERSION = "FNDDS 2021-2023"
TYPICAL = "Quantity not specified"
MAX_GRAMS = 5000  # same limit as portion_sizes.grams


def main(zip_path, out_path):
    with zipfile.ZipFile(zip_path) as z:
        foods = json.loads(z.read(z.namelist()[0]))["SurveyFoods"]

    values, skipped = [], 0
    for food in foods:
        if not food["foodNutrients"]:
            continue  # this food was not imported (no energy value)
        seen = set()
        for portion in food.get("foodPortions", []):
            grams = round(float(portion["gramWeight"]), 2)
            label = portion["portionDescription"].strip()
            is_default = label == TYPICAL
            if is_default:
                label = "1 typical serving"
            if not label or label in seen or not 0 < grams <= MAX_GRAMS:
                skipped += 1
                continue
            seen.add(label)
            note = f"{FNDDS_VERSION} food code {food['foodCode']}"
            row = [str(food["fdcId"]), label, grams, note]
            values.append(
                "  (" + ", ".join(sql_value(v) for v in row) + f", {'true' if is_default else 'false'})"
            )

    with open(out_path, "w", encoding="utf-8") as f:
        f.write(
            "-- Generated by scripts/import/fndds_portions_to_sql.py — do not edit by hand.\n"
            "-- Source: U.S. Department of Agriculture, Agricultural Research Service.\n"
            "-- FoodData Central (FNDDS 2021-2023). Public domain (CC0 1.0).\n\n"
            "insert into public.portion_sizes (food_id, label, grams, source, source_note, is_default)\n"
            "select f.id, v.label, v.grams, 'usda_fndds', v.note, v.is_default\n"
            "from (values\n" + ",\n".join(values) + "\n"
            ") as v(fdc_id, label, grams, note, is_default)\n"
            "join public.foods f on f.source = 'usda_fdc' and f.source_food_id = v.fdc_id\n"
            "on conflict (food_id, label) do update set\n"
            "  grams = excluded.grams, source = excluded.source,\n"
            "  source_note = excluded.source_note, is_default = excluded.is_default;\n"
        )
    print(f"Wrote {len(values)} portions to {out_path}")
    print(f"Skipped {skipped} (duplicate label, empty, or weight out of range)")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(*sys.argv[1:])
