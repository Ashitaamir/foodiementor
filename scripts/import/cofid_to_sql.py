"""
Build a SQL migration that loads UK CoFID 2021 into public.foods.

Source: McCance and Widdowson's Composition of Foods Integrated Dataset 2021
(Public Health England). Contains public sector information licensed under
the Open Government Licence v3.0.

Usage:
  python3 scripts/import/cofid_to_sql.py data/raw/cofid/CoFID_2021.xlsx OUTPUT.sql

Uses only the Python standard library (an .xlsx file is a zip of XML files).
"""
import re
import sys
import zipfile
import xml.etree.ElementTree as ET

NS = {"m": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}
REL_ID = "{http://schemas.openxmlformats.org/officeDocument/2006/relationships}id"
SHEET_NAME = "1.3 Proximates"
SOURCE_VERSION = "CoFID 2021"

# Column position -> expected header text (checked, so a changed file fails loudly)
COLS = {
    "code": (0, "Food Code"),
    "name": (1, "Food Name"),
    "group": (3, "Group"),
    "protein_g": (9, "Protein (g)"),
    "fat_g": (10, "Fat (g)"),
    "carbs_g": (11, "Carbohydrate (g)"),
    "energy_kcal": (12, "Energy (kcal) (kcal)"),
    "fibre_g": (25, "AOAC fibre (g)"),
}


def col_index(cell_ref):
    n = 0
    for ch in re.match(r"[A-Z]+", cell_ref).group():
        n = n * 26 + ord(ch) - 64
    return n - 1


def read_sheet(path, sheet_name):
    """Return the sheet's rows as lists of cell text."""
    z = zipfile.ZipFile(path)
    text_tag = "{%s}t" % NS["m"]
    shared = [
        "".join(t.text or "" for t in si.iter(text_tag))
        for si in ET.fromstring(z.read("xl/sharedStrings.xml")).findall("m:si", NS)
    ]
    workbook = ET.fromstring(z.read("xl/workbook.xml"))
    rels = ET.fromstring(z.read("xl/_rels/workbook.xml.rels"))
    targets = {r.get("Id"): r.get("Target").lstrip("/") for r in rels}
    sheet = next(s for s in workbook.find("m:sheets", NS) if s.get("name") == sheet_name)
    target = targets[sheet.get(REL_ID)]
    if not target.startswith("xl/"):
        target = "xl/" + target

    rows = []
    for row in ET.fromstring(z.read(target)).find("m:sheetData", NS).findall("m:row", NS):
        cells = {}
        for c in row.findall("m:c", NS):
            v = c.find("m:v", NS)
            if v is not None:
                cells[col_index(c.get("r"))] = shared[int(v.text)] if c.get("t") == "s" else v.text
        width = max(cells, default=-1) + 1
        rows.append([cells.get(i, "").strip() for i in range(width)])
    return rows


def to_number(raw):
    """'Tr' (trace) -> 0, 'N' (not measured) or blank -> None, else a number."""
    if raw == "Tr":
        return 0.0
    if raw in ("", "N"):
        return None
    return round(float(raw), 2)


def sql_value(v):
    if v is None:
        return "null"
    if isinstance(v, float):
        return f"{v:.2f}"
    return "'" + v.replace("'", "''") + "'"


def main(xlsx_path, out_path):
    rows = read_sheet(xlsx_path, SHEET_NAME)
    header = rows[0]
    for field, (i, expected) in COLS.items():
        if i >= len(header) or header[i] != expected:
            sys.exit(f"Unexpected column {i} for {field}: {header[i] if i < len(header) else None!r}")

    get = lambda r, f: r[COLS[f][0]] if COLS[f][0] < len(r) else ""
    seen, values = set(), []
    skipped = {"no kcal": 0, "alcoholic (per 100 ml)": 0}

    for r in rows[3:]:  # rows 1-3 are headers
        code = get(r, "code")
        if not code:
            continue
        if code in seen:
            # CoFID 2021 reuses one code for two different foods (13-669:
            # roasted aubergine and raw watercress). Keep both; mark ours.
            n = 2
            while f"{code}-dup{n}" in seen:
                n += 1
            code = f"{code}-dup{n}"
        if get(r, "group").startswith("Q"):
            skipped["alcoholic (per 100 ml)"] += 1
            continue
        kcal = to_number(get(r, "energy_kcal"))
        if kcal is None:
            skipped["no kcal"] += 1
            continue
        seen.add(code)
        row = [get(r, "name"), "uk_cofid", code, SOURCE_VERSION, kcal] + [
            to_number(get(r, f)) for f in ("protein_g", "carbs_g", "fat_g", "fibre_g")
        ]
        values.append("  (" + ", ".join(sql_value(v) for v in row) + ")")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write(
            "-- Generated by scripts/import/cofid_to_sql.py — do not edit by hand.\n"
            "-- Source: McCance and Widdowson's Composition of Foods Integrated Dataset 2021.\n"
            "-- Contains public sector information licensed under the Open Government Licence v3.0.\n\n"
            "insert into public.foods\n"
            "  (name, source, source_food_id, source_version, energy_kcal, protein_g, carbs_g, fat_g, fibre_g)\n"
            "values\n" + ",\n".join(values) + "\n"
            "on conflict (source, source_food_id) do update set\n"
            "  name = excluded.name,\n"
            "  source_version = excluded.source_version,\n"
            "  energy_kcal = excluded.energy_kcal,\n"
            "  protein_g = excluded.protein_g,\n"
            "  carbs_g = excluded.carbs_g,\n"
            "  fat_g = excluded.fat_g,\n"
            "  fibre_g = excluded.fibre_g;\n"
        )
    print(f"Wrote {len(values)} foods to {out_path}")
    for reason, n in skipped.items():
        print(f"Skipped {n}: {reason}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
