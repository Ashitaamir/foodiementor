"""
Build a SQL migration that loads USDA FNDDS 2021-2023 foods into public.foods.

Source: U.S. Department of Agriculture, Agricultural Research Service.
FoodData Central (FNDDS 2021-2023). Public domain (CC0 1.0).
Values are per 100 g (FNDDS reports drinks per 100 g too).

Usage:
  python3 scripts/import/fndds_to_sql.py data/raw/fndds/FNDDS_2021-2023.zip OUTPUT.sql
"""
import json
import sys
import zipfile

from cofid_to_sql import sql_value

SOURCE_VERSION = "FNDDS 2021-2023"

# USDA nutrient numbers -> our columns
NUTRIENTS = {
    "208": "energy_kcal",  # Energy (kcal)
    "203": "protein_g",    # Protein (g)
    "205": "carbs_g",      # Carbohydrate, by difference (g)
    "204": "fat_g",        # Total lipid (fat) (g)
    "291": "fibre_g",      # Fiber, total dietary (g)
}
COLUMNS = ["energy_kcal", "protein_g", "carbs_g", "fat_g", "fibre_g"]


def main(zip_path, out_path):
    with zipfile.ZipFile(zip_path) as z:
        foods = json.loads(z.read(z.namelist()[0]))["SurveyFoods"]

    values, skipped = [], 0
    for food in foods:
        amounts = {
            NUTRIENTS[n["nutrient"]["number"]]: round(float(n["amount"]), 2)
            for n in food["foodNutrients"]
            if n["nutrient"]["number"] in NUTRIENTS
        }
        if "energy_kcal" not in amounts:
            skipped += 1
            continue
        row = [food["description"], "usda_fdc", str(food["fdcId"]), SOURCE_VERSION]
        row += [amounts.get(c) for c in COLUMNS]
        values.append("  (" + ", ".join(sql_value(v) for v in row) + ")")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write(
            "-- Generated by scripts/import/fndds_to_sql.py — do not edit by hand.\n"
            "-- Source: U.S. Department of Agriculture, Agricultural Research Service.\n"
            "-- FoodData Central (FNDDS 2021-2023). Public domain (CC0 1.0).\n\n"
            "insert into public.foods\n"
            "  (name, source, source_food_id, source_version, energy_kcal, protein_g, carbs_g, fat_g, fibre_g)\n"
            "values\n" + ",\n".join(values) + "\n"
            "on conflict (source, source_food_id) do update set\n"
            "  name = excluded.name,\n"
            "  source_version = excluded.source_version,\n"
            "  energy_kcal = excluded.energy_kcal,\n"
            "  protein_g = excluded.protein_g,\n"
            "  carbs_g = excluded.carbs_g,\n"
            "  fat_g = excluded.fat_g,\n"
            "  fibre_g = excluded.fibre_g;\n"
        )
    print(f"Wrote {len(values)} foods to {out_path}")
    print(f"Skipped {skipped}: no energy value")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(*sys.argv[1:])
