"""
Build a SQL migration that loads USDA SR Legacy (April 2018) into public.foods,
plus its measured household portions (e.g. "1 cup", "1 tbsp") into public.portion_sizes.
SR Legacy covers basic and raw ingredients (dry pasta, uncooked rice, flour, oils...).

Source: U.S. Department of Agriculture, Agricultural Research Service.
FoodData Central (SR Legacy, April 2018). Public domain (CC0 1.0).

Usage:
  python3 scripts/import/sr_legacy_to_sql.py data/raw/sr_legacy/SR_Legacy_2018-04.zip OUTPUT.sql
"""
import json
import sys
import zipfile

from cofid_to_sql import sql_value

SOURCE_VERSION = "SR Legacy 2018-04"
MAX_GRAMS = 5000  # same limit as portion_sizes.grams

NUTRIENTS = {
    "208": "energy_kcal",
    "203": "protein_g",
    "205": "carbs_g",
    "204": "fat_g",
    "291": "fibre_g",
}
COLUMNS = ["energy_kcal", "protein_g", "carbs_g", "fat_g", "fibre_g"]


def portion_rows(food):
    """SR Legacy stores e.g. amount 2 + modifier "oz" (57 g); we store it per 1 unit: "1 oz" (28.5 g)."""
    rows, seen = [], set()
    for portion in sorted(food.get("foodPortions", []), key=lambda p: p.get("sequenceNumber", 0)):
        modifier = (portion.get("modifier") or portion.get("portionDescription") or "").strip()
        amount = float(portion.get("amount") or 0)
        if not modifier or amount <= 0:
            continue
        grams = round(float(portion["gramWeight"]) / amount, 2)
        label = f"1 {modifier}"
        if label in seen or not 0 < grams <= MAX_GRAMS:
            continue
        seen.add(label)
        rows.append((label, grams, modifier.lower() == "serving"))
    return rows


def main(zip_path, out_path):
    with zipfile.ZipFile(zip_path) as z:
        foods = json.loads(z.read(z.namelist()[0]))["SRLegacyFoods"]

    food_values, portion_values, skipped = [], [], 0
    for food in foods:
        amounts = {
            NUTRIENTS[n["nutrient"]["number"]]: round(float(n["amount"]), 2)
            for n in food["foodNutrients"]
            if n["nutrient"].get("number") in NUTRIENTS and "amount" in n
        }
        if "energy_kcal" not in amounts:
            skipped += 1
            continue
        fdc_id = str(food["fdcId"])
        row = [food["description"], "usda_fdc", fdc_id, SOURCE_VERSION] + [amounts.get(c) for c in COLUMNS]
        food_values.append("  (" + ", ".join(sql_value(v) for v in row) + ")")
        note = f"{SOURCE_VERSION} fdcId {fdc_id}"
        for label, grams, is_default in portion_rows(food):
            portion_values.append(
                "  ("
                + ", ".join(sql_value(v) for v in [fdc_id, label, grams, note])
                + f", {'true' if is_default else 'false'})"
            )

    with open(out_path, "w", encoding="utf-8") as f:
        f.write(
            "-- Generated by scripts/import/sr_legacy_to_sql.py — do not edit by hand.\n"
            "-- Source: U.S. Department of Agriculture, Agricultural Research Service.\n"
            "-- FoodData Central (SR Legacy, April 2018). Public domain (CC0 1.0).\n\n"
            "-- Allow SR Legacy as a source of measured portion sizes\n"
            "alter table public.portion_sizes drop constraint portion_sizes_source_check;\n"
            "alter table public.portion_sizes add constraint portion_sizes_source_check\n"
            "  check (source in ('usda_fndds', 'usda_sr_legacy', 'uk_fsa', 'foodiementor_estimate'));\n\n"
            "insert into public.foods\n"
            "  (name, source, source_food_id, source_version, energy_kcal, protein_g, carbs_g, fat_g, fibre_g)\n"
            "values\n" + ",\n".join(food_values) + "\n"
            "on conflict (source, source_food_id) do update set\n"
            "  name = excluded.name,\n"
            "  source_version = excluded.source_version,\n"
            "  energy_kcal = excluded.energy_kcal,\n"
            "  protein_g = excluded.protein_g,\n"
            "  carbs_g = excluded.carbs_g,\n"
            "  fat_g = excluded.fat_g,\n"
            "  fibre_g = excluded.fibre_g;\n\n"
            "insert into public.portion_sizes (food_id, label, grams, source, source_note, is_default)\n"
            "select f.id, v.label, v.grams, 'usda_sr_legacy', v.note, v.is_default\n"
            "from (values\n" + ",\n".join(portion_values) + "\n"
            ") as v(fdc_id, label, grams, note, is_default)\n"
            "join public.foods f on f.source = 'usda_fdc' and f.source_food_id = v.fdc_id\n"
            "on conflict (food_id, label) do update set\n"
            "  grams = excluded.grams, source = excluded.source,\n"
            "  source_note = excluded.source_note, is_default = excluded.is_default;\n"
        )
    print(f"Wrote {len(food_values)} foods and {len(portion_values)} portions to {out_path}")
    print(f"Skipped {skipped} foods with no energy value")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(*sys.argv[1:])
